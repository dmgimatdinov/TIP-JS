-- Схема учебной базы Лекции 6.
-- Выполнять в новой пустой базе tip_tasks от владельца tip_app.
-- Запуск: psql -X -h 127.0.0.1 -U tip_app -d tip_tasks -v ON_ERROR_STOP=1 -1 -f sql/01_schema.sql

-- Сначала categories, затем tasks: внешний ключ требует существования ссылочной таблицы.
CREATE TABLE public.categories (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  CONSTRAINT categories_pkey PRIMARY KEY (id),
  CONSTRAINT categories_id_positive CHECK (id > 0),
  CONSTRAINT categories_name_key UNIQUE (name),
  CONSTRAINT categories_name_valid CHECK (
    length(btrim(name)) BETWEEN 1 AND 100
  )
);

CREATE TABLE public.tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  title text NOT NULL,
  completed boolean NOT NULL DEFAULT false,
  priority text NOT NULL,
  category_id integer NOT NULL,
  CONSTRAINT tasks_pkey PRIMARY KEY (id),
  CONSTRAINT tasks_id_positive CHECK (id > 0),
  CONSTRAINT tasks_title_valid CHECK (
    length(btrim(title)) BETWEEN 1 AND 100
  ),
  CONSTRAINT tasks_priority_valid CHECK (
    priority IN ('low', 'medium', 'high')
  ),
  CONSTRAINT tasks_category_fk
    FOREIGN KEY (category_id)
    REFERENCES public.categories (id)
    ON DELETE RESTRICT
);

-- Индекс по category_id ускоряет JOIN и фильтрацию по категории.
CREATE INDEX tasks_category_id_idx ON public.tasks (category_id);
